export type Key = keyof typeof D;
export const makeT = (lang: Lang) => (k: Key, v?: Record<string, string | number>): string => {
  let s: string = D[k][lang === "id" ? 0 : 1];
  if (v) for (const x in v) s = s.split(`{${x}}`).join(String(v[x]));
  return s;
};
export type TFn = ReturnType<typeof makeT>;
